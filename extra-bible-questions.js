  const existingQuestions = new Set(
    [...MCQ, ...TF].map(item => normalizeText(item.q))
  );

  const filteredMCQ = EXTRA_MCQ.filter(item => {
    const key = normalizeText(item.q);
    if (existingQuestions.has(key)) return false;
    existingQuestions.add(key);
    return true;
  });

